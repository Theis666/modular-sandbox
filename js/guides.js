// Guided Builds: step-by-step recipes that build a target patch (see ADR 0006).
// Step kinds:
//   add   – add a module of `type`; remembered under the alias `as`
//   cable – connect [alias, jack] → [alias, jack]
//   set   – move a control until `test(value)` is true
//   play  – play at least two notes on the keys
//   next  – read / listen, then tap Next
// `base` names an Example Patch to start from (its module ids become aliases); null = empty rack.

const add = (type, as, title, text, why) => ({ do: 'add', type, as, title, text, why });
const cable = (from, to, title, text, why) => ({ do: 'cable', from, to, title, text, why });
const set = (mod, param, test, title, text, why) => ({ do: 'set', mod, param, test, title, text, why });
const play = (title, text, why) => ({ do: 'play', title, text, why });
const next = (title, text, why) => ({ do: 'next', title, text, why });

